import assert from "node:assert/strict";
import { mkdtemp, writeFile, mkdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";
import { createJiti } from "jiti";
import { chromium } from "playwright-core";

test("desktop executor restores the exact headless target without returning credentials or closing its browser", { timeout: 30000 }, async t => {
  const root = await mkdtemp(path.join(tmpdir(), "piora-background-login-"));
  const profile = path.join(root, "piora", "browser-profile"); await mkdir(profile, { recursive: true });
  const stubPath = path.join(root, "electron.cjs");
  await writeFile(stubPath, `module.exports={app:{isPackaged:false,getPath:()=>${JSON.stringify(root)}},safeStorage:{isEncryptionAvailable:()=>true,encryptString:s=>Buffer.from(s),decryptString:b=>b.toString()}};`);
  const loader = createJiti(import.meta.url, { alias: { electron: stubPath } });
  const { getCredentialVault } = await loader.import("../desktop/src/credential-vault-ipc.ts");
  const { recoverBackgroundLogin } = await loader.import("../desktop/src/background-login.ts");
  const store = getCredentialVault();
  store.initialize("fixture-master-password");
  const url = "https://background.example.com/login";
  store.save({ name: "Test", url, username: "fixture-user", password: "fixture-secret", autoLogin: true });
  store.lock();
  const context = await chromium.launchPersistentContext(profile, { headless: true, channel: process.platform === "win32" ? "msedge" : "chromium", args: ["--remote-debugging-port=0", "--remote-debugging-address=127.0.0.1"] });
  t.after(async () => { await context.close(); await rm(root, { recursive: true, force: true }); });
  await context.route("https://background.example.com/**", route => route.fulfill({ contentType: "text/html", body: '<form method="post"><input name="user"><input type="password"><button>Sign in</button></form><script>document.querySelector("form").onsubmit=e=>{e.preventDefault();document.cookie="fixture=ok;path=/";history.replaceState(null,"","/home");document.body.innerHTML="<button>Sign out</button>"}</script>' }));
  const unrelated = await context.newPage(); await unrelated.goto("about:blank");
  const page = await context.newPage(); await page.goto(url);
  const cdp = await context.newCDPSession(page); const { targetInfo } = await cdp.send("Target.getTargetInfo"); await cdp.detach();
  const result = await recoverBackgroundLogin(root, "test-request", targetInfo.targetId, { graceMs: 0, timeoutMs: 5000 });
  assert.deepEqual(result, { status: "ready", url: "https://background.example.com/home" });
  assert.equal(page.isClosed(), true);
  assert.equal(unrelated.isClosed(), false);
  assert.ok((await context.cookies()).some(cookie => cookie.name === "fixture" && cookie.value === "ok"));
  assert.doesNotMatch(JSON.stringify(result), /fixture-user|fixture-secret/);
  await assert.rejects(recoverBackgroundLogin(root, "invalid", "../../other"), /Invalid browser target/);
});
